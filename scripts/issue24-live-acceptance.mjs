import assert from "node:assert/strict";
import { chromium, expect } from "@playwright/test";

const required = ["DEMO_ACCEPTANCE_URL", "DEMO_ACCEPTANCE_PREVIEW_PASSWORD", "DEMO_ACCEPTANCE_PASSWORD"];
for (const key of required) if (!process.env[key]) throw new Error("Missing required acceptance configuration: " + key);
const baseURL = process.env.DEMO_ACCEPTANCE_URL;
assert.equal(new URL(baseURL).origin, "https://cheng-tea-password-demo.onrender.com", "Acceptance is limited to the isolated password demo");
assert.equal(new URL(baseURL).pathname, "/", "Acceptance URL must be the site root");
const password = process.env.DEMO_ACCEPTANCE_PASSWORD;
const customerName = "流程驗收" + Date.now();
