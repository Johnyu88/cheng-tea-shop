  checkpoint(8);
  await gallery.setInputFiles({ name: "gallery-preview.png", mimeType: "image/png", buffer: png });
  await expect(card).toContainText("gallery-preview.png");
  await gallery.setInputFiles({ name: "confirmed-packing.png", mimeType: "image/png", buffer: png });
  await expect(card).toContainText("confirmed-packing.png");
